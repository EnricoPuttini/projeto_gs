-- ZELO - DDL Oracle (mesmo modelo usado pelos DAOs em br.com.zelo.dao)
-- Convencoes: prefixo ZL_, PK IDENTITY, constraints nomeadas (PK_, FK_, CK_, UQ_).
-- Flags booleanas = NUMBER(1) com CK 0/1. Datas/horas = TIMESTAMP no fuso America/Sao_Paulo
-- (o backend usa LocalDateTime derivado do Clock injetado).
-- IDENTITY e BY DEFAULT para o seed poder fixar IDs; o seed realinha o contador no final.
-- Comandos terminam em ";" e nao ha PL/SQL, entao o mesmo arquivo roda via sqlplus e via JDBC.

CREATE TABLE ZL_UBS (
  ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOME      VARCHAR2(120) NOT NULL,
  ENDERECO  VARCHAR2(200) NOT NULL,
  LAT       NUMBER(9,6)   NOT NULL,
  LNG       NUMBER(9,6)   NOT NULL,
  CONSTRAINT PK_UBS PRIMARY KEY (ID)
);

CREATE TABLE ZL_ESPECIALIDADE (
  ID    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOME  VARCHAR2(80) NOT NULL,
  CONSTRAINT PK_ESPEC PRIMARY KEY (ID),
  CONSTRAINT UQ_ESPEC_NOME UNIQUE (NOME)
);

CREATE TABLE ZL_PACIENTE (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOME           VARCHAR2(120) NOT NULL,
  DT_NASC        DATE          NOT NULL,
  TELEFONE       VARCHAR2(20)  NOT NULL,
  LAT            NUMBER(9,6)   NOT NULL,
  LNG            NUMBER(9,6)   NOT NULL,
  HIPERTENSAO   NUMBER(1) DEFAULT 0 NOT NULL,
  DIABETES      NUMBER(1) DEFAULT 0 NOT NULL,
  DEFICIENCIA   NUMBER(1) DEFAULT 0 NOT NULL,
  BOLSA_FAMILIA NUMBER(1) DEFAULT 0 NOT NULL,
  GESTANTE      NUMBER(1) DEFAULT 0 NOT NULL,
  PCD           NUMBER(1) DEFAULT 0 NOT NULL,
  FALTAS_ANT    NUMBER(3) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PACIENTE PRIMARY KEY (ID),
  CONSTRAINT CK_PAC_FLAGS CHECK (
    HIPERTENSAO IN (0,1) AND DIABETES IN (0,1) AND DEFICIENCIA IN (0,1) AND
    BOLSA_FAMILIA IN (0,1) AND GESTANTE IN (0,1) AND PCD IN (0,1)),
  CONSTRAINT CK_PAC_FALTAS CHECK (FALTAS_ANT >= 0)
);

CREATE TABLE ZL_CONSULTA (
  ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
  PACIENTE_ID      NUMBER        NOT NULL,
  UBS_ID           NUMBER        NOT NULL,
  ESPEC_ID         NUMBER        NOT NULL,
  DATA_HORA        TIMESTAMP     NOT NULL,
  STATUS           VARCHAR2(24)  NOT NULL,
  RISCO_FALTA      NUMBER(4,3),
  ORIGEM           VARCHAR2(10)  DEFAULT 'NORMAL' NOT NULL,
  LEMBRETE_ENVIADO NUMBER(1)     DEFAULT 0 NOT NULL,
  CRIADA_EM        TIMESTAMP     NOT NULL,
  CONSTRAINT PK_CONSULTA PRIMARY KEY (ID),
  CONSTRAINT FK_CONS_PAC   FOREIGN KEY (PACIENTE_ID) REFERENCES ZL_PACIENTE (ID),
  CONSTRAINT FK_CONS_UBS   FOREIGN KEY (UBS_ID)      REFERENCES ZL_UBS (ID),
  CONSTRAINT FK_CONS_ESPEC FOREIGN KEY (ESPEC_ID)    REFERENCES ZL_ESPECIALIDADE (ID),
  CONSTRAINT CK_CONS_STATUS CHECK (STATUS IN
    ('AGENDADA','AGUARDANDO_CONFIRMACAO','CONFIRMADA','CANCELADA','NAO_RESPONDIDA','REALIZADA','FALTA')),
  CONSTRAINT CK_CONS_ORIGEM CHECK (ORIGEM IN ('NORMAL','ENCAIXE')),
  CONSTRAINT CK_CONS_RISCO  CHECK (RISCO_FALTA IS NULL OR RISCO_FALTA BETWEEN 0 AND 1),
  CONSTRAINT CK_CONS_LEMB   CHECK (LEMBRETE_ENVIADO IN (0,1))
);
CREATE INDEX IX_CONS_UBS_DATA ON ZL_CONSULTA (UBS_ID, DATA_HORA);
CREATE INDEX IX_CONS_PAC ON ZL_CONSULTA (PACIENTE_ID);

CREATE TABLE ZL_FILA (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  PACIENTE_ID  NUMBER       NOT NULL,
  UBS_ID       NUMBER       NOT NULL,
  ESPEC_ID     NUMBER       NOT NULL,
  DATA_ENTRADA TIMESTAMP    NOT NULL,
  GRAVIDADE    NUMBER(1)    NOT NULL,
  STATUS       VARCHAR2(10) DEFAULT 'ATIVA' NOT NULL,
  CONSTRAINT PK_FILA PRIMARY KEY (ID),
  CONSTRAINT FK_FILA_PAC   FOREIGN KEY (PACIENTE_ID) REFERENCES ZL_PACIENTE (ID),
  CONSTRAINT FK_FILA_UBS   FOREIGN KEY (UBS_ID)      REFERENCES ZL_UBS (ID),
  CONSTRAINT FK_FILA_ESPEC FOREIGN KEY (ESPEC_ID)    REFERENCES ZL_ESPECIALIDADE (ID),
  CONSTRAINT CK_FILA_GRAV   CHECK (GRAVIDADE BETWEEN 1 AND 3),
  CONSTRAINT CK_FILA_STATUS CHECK (STATUS IN ('ATIVA','ATENDIDA','SAIU'))
);
-- Um paciente so pode ter UMA entrada ATIVA por UBS+especialidade.
-- Indice unico funcional: linhas nao-ATIVA viram (NULL,NULL,NULL) e Oracle ignora chaves totalmente nulas.
CREATE UNIQUE INDEX UQ_FILA_ATIVA ON ZL_FILA (
  CASE WHEN STATUS = 'ATIVA' THEN PACIENTE_ID END,
  CASE WHEN STATUS = 'ATIVA' THEN UBS_ID END,
  CASE WHEN STATUS = 'ATIVA' THEN ESPEC_ID END);
CREATE INDEX IX_FILA_BUSCA ON ZL_FILA (UBS_ID, ESPEC_ID, STATUS);

CREATE TABLE ZL_VAGA (
  ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
  CONSULTA_ORIGEM_ID NUMBER       NOT NULL,
  UBS_ID             NUMBER       NOT NULL,
  ESPEC_ID           NUMBER       NOT NULL,
  DATA_HORA          TIMESTAMP    NOT NULL,
  STATUS             VARCHAR2(12) DEFAULT 'ABERTA' NOT NULL,
  CRIADA_EM          TIMESTAMP    NOT NULL,
  CONSTRAINT PK_VAGA PRIMARY KEY (ID),
  CONSTRAINT FK_VAGA_CONS  FOREIGN KEY (CONSULTA_ORIGEM_ID) REFERENCES ZL_CONSULTA (ID),
  CONSTRAINT FK_VAGA_UBS   FOREIGN KEY (UBS_ID)   REFERENCES ZL_UBS (ID),
  CONSTRAINT FK_VAGA_ESPEC FOREIGN KEY (ESPEC_ID) REFERENCES ZL_ESPECIALIDADE (ID),
  CONSTRAINT UQ_VAGA_CONS  UNIQUE (CONSULTA_ORIGEM_ID),
  CONSTRAINT CK_VAGA_STATUS CHECK (STATUS IN ('ABERTA','EM_OFERTA','PREENCHIDA','PERDIDA'))
);

CREATE TABLE ZL_OFERTA (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  VAGA_ID     NUMBER       NOT NULL,
  PACIENTE_ID NUMBER       NOT NULL,
  FILA_ID     NUMBER       NOT NULL,
  ENVIADA_EM  TIMESTAMP    NOT NULL,
  EXPIRA_EM   TIMESTAMP    NOT NULL,
  STATUS      VARCHAR2(10) DEFAULT 'PENDENTE' NOT NULL,
  CONSTRAINT PK_OFERTA PRIMARY KEY (ID),
  CONSTRAINT FK_OFE_VAGA FOREIGN KEY (VAGA_ID)     REFERENCES ZL_VAGA (ID),
  CONSTRAINT FK_OFE_PAC  FOREIGN KEY (PACIENTE_ID) REFERENCES ZL_PACIENTE (ID),
  CONSTRAINT FK_OFE_FILA FOREIGN KEY (FILA_ID)     REFERENCES ZL_FILA (ID),
  CONSTRAINT CK_OFE_STATUS CHECK (STATUS IN ('PENDENTE','ACEITA','RECUSADA','EXPIRADA')),
  CONSTRAINT CK_OFE_VALID  CHECK (EXPIRA_EM > ENVIADA_EM)
);
-- Segunda barreira da regra "nunca duas ofertas PENDENTES para a mesma vaga"
-- (a primeira e o SELECT ... FOR UPDATE na linha da vaga, feito no DAO).
CREATE UNIQUE INDEX UQ_OFE_PEND ON ZL_OFERTA (CASE WHEN STATUS = 'PENDENTE' THEN VAGA_ID END);
CREATE INDEX IX_OFE_PAC ON ZL_OFERTA (PACIENTE_ID, STATUS);

CREATE TABLE ZL_MENSAGEM (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  PACIENTE_ID NUMBER         NOT NULL,
  DIRECAO     VARCHAR2(6)    NOT NULL,
  CANAL       VARCHAR2(10)   NOT NULL,
  TEXTO       VARCHAR2(1000) NOT NULL,
  TIPO        VARCHAR2(30)   NOT NULL,
  CRIADA_EM   TIMESTAMP      NOT NULL,
  CONSTRAINT PK_MENSAGEM PRIMARY KEY (ID),
  CONSTRAINT FK_MSG_PAC FOREIGN KEY (PACIENTE_ID) REFERENCES ZL_PACIENTE (ID),
  CONSTRAINT CK_MSG_DIR   CHECK (DIRECAO IN ('ENTRADA','SAIDA')),
  CONSTRAINT CK_MSG_CANAL CHECK (CANAL IN ('APP','WHATSAPP'))
);
CREATE INDEX IX_MSG_PAC ON ZL_MENSAGEM (PACIENTE_ID, CRIADA_EM);

CREATE TABLE ZL_LOCAL_SALVO (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  PACIENTE_ID NUMBER        NOT NULL,
  APELIDO     VARCHAR2(60)  NOT NULL,
  LAT         NUMBER(9,6)   NOT NULL,
  LNG         NUMBER(9,6)   NOT NULL,
  TIPO        VARCHAR2(20)  DEFAULT 'CASA' NOT NULL,
  INTENSIDADE VARCHAR2(12)  DEFAULT 'VIBRAR' NOT NULL,
  ATIVO       NUMBER(1)     DEFAULT 1 NOT NULL,
  CONSTRAINT PK_LOCAL PRIMARY KEY (ID),
  CONSTRAINT FK_LOCAL_PAC FOREIGN KEY (PACIENTE_ID) REFERENCES ZL_PACIENTE (ID),
  CONSTRAINT CK_LOCAL_TIPO  CHECK (TIPO IN ('CASA','TRABALHO','FAMILIA','OUTRO')),
  CONSTRAINT CK_LOCAL_INT   CHECK (INTENSIDADE IN ('SILENCIOSO','VIBRAR','ALARME')),
  CONSTRAINT CK_LOCAL_ATIVO CHECK (ATIVO IN (0,1))
);

CREATE TABLE ZL_AREA_RISCO (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOME       VARCHAR2(120) NOT NULL,
  LAT        NUMBER(9,6)   NOT NULL,
  LNG        NUMBER(9,6)   NOT NULL,
  RAIO_M     NUMBER(6)     NOT NULL,
  LIMIAR_MM  NUMBER(5,1)   NOT NULL,
  CONSTRAINT PK_AREA PRIMARY KEY (ID),
  CONSTRAINT CK_AREA_RAIO   CHECK (RAIO_M > 0),
  CONSTRAINT CK_AREA_LIMIAR CHECK (LIMIAR_MM > 0)
);

CREATE TABLE ZL_ABRIGO (
  ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOME       VARCHAR2(120) NOT NULL,
  ENDERECO   VARCHAR2(200) NOT NULL,
  LAT        NUMBER(9,6)   NOT NULL,
  LNG        NUMBER(9,6)   NOT NULL,
  CAPACIDADE NUMBER(6)     NOT NULL,
  CONSTRAINT PK_ABRIGO PRIMARY KEY (ID),
  CONSTRAINT CK_ABRIGO_CAP CHECK (CAPACIDADE > 0)
);

CREATE TABLE ZL_ALERTA (
  ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
  LOCAL_ID            NUMBER       NOT NULL,
  AREA_ID             NUMBER       NOT NULL,
  ABRIGO_ID           NUMBER,
  CHUVA_MM            NUMBER(6,1)  NOT NULL,
  NIVEL               VARCHAR2(10) NOT NULL,
  CRIADO_EM           TIMESTAMP    NOT NULL,
  JANELA              TIMESTAMP    NOT NULL,
  CONFIRMADO_SEGURO_EM TIMESTAMP,
  CONSTRAINT PK_ALERTA PRIMARY KEY (ID),
  CONSTRAINT FK_ALE_LOCAL  FOREIGN KEY (LOCAL_ID)  REFERENCES ZL_LOCAL_SALVO (ID),
  CONSTRAINT FK_ALE_AREA   FOREIGN KEY (AREA_ID)   REFERENCES ZL_AREA_RISCO (ID),
  CONSTRAINT FK_ALE_ABRIGO FOREIGN KEY (ABRIGO_ID) REFERENCES ZL_ABRIGO (ID),
  CONSTRAINT CK_ALE_NIVEL CHECK (NIVEL IN ('ATENCAO','ALTO','CRITICO')),
  -- JANELA = hora cheia da previsao; impede alertar o mesmo local/area duas vezes na mesma hora.
  CONSTRAINT UQ_ALE_JANELA UNIQUE (LOCAL_ID, AREA_ID, JANELA)
);
